import Foundation
import AppKit
import CryptoKit
import UniformTypeIdentifiers

public protocol PasteboardReadable {
    var pasteboardTypes: [NSPasteboard.PasteboardType] { get }
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
    func data(forType dataType: NSPasteboard.PasteboardType) -> Data?
    func fileURLs() -> [URL]
}

extension NSPasteboard: PasteboardReadable {
    public var pasteboardTypes: [NSPasteboard.PasteboardType] {
        types ?? []
    }

    public func fileURLs() -> [URL] {
        (readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
    }
}

public struct CapturedPayload {
    public let item: ClipItem
    public let imageData: Data?
    public let rtfData: Data?
    public let htmlData: Data?
}

@MainActor
public final class ClipboardMonitor {
    private var timer: Timer?
    private var lastChangeCount: Int
    private var suppressedChangeCounts: Set<Int> = []

    public var isPaused: Bool = false
    public var onCapture: ((CapturedPayload) -> Void)?

    public static let sensitivePasteboardTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.bitwarden.desktop",
        "com.apple.Security",
        "PasswordPboardType"
    ]

    public init(initialChangeCount: Int? = nil) {
        self.lastChangeCount = initialChangeCount ?? NSPasteboard.general.changeCount
    }

    public func start(settingsProvider: @escaping () -> AppSettings) {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let newTimer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.poll(settings: settingsProvider())
            }
        }
        RunLoop.main.add(newTimer, forMode: .common)
        self.timer = newTimer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public func markInternalWrite(changeCount: Int) {
        suppressedChangeCounts.insert(changeCount)
        lastChangeCount = changeCount
    }

    private func poll(settings: AppSettings) {
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        if suppressedChangeCounts.remove(currentCount) != nil {
            return
        }
        guard !isPaused else { return }

        if settings.ignoreSensitiveContent {
            let types = Set((pasteboard.types ?? []).map { $0.rawValue })
            if !types.isDisjoint(with: Self.sensitivePasteboardTypes) {
                return
            }
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleID = frontApp?.bundleIdentifier
        let appName = frontApp?.localizedName

        // Never record from our own bundle if accidental, or excluded apps
        if let bundleID {
            if bundleID == Bundle.main.bundleIdentifier {
                return
            }
            if settings.excludedBundleIDs.contains(bundleID) {
                return
            }
        }

        if let payload = extractPayload(
            from: pasteboard,
            sourceBundleID: bundleID,
            sourceAppName: appName,
            ignoreSensitive: settings.ignoreSensitiveContent
        ) {
            onCapture?(payload)
        }
    }

    public func extractPayload(
        from pasteboard: PasteboardReadable,
        sourceBundleID: String?,
        sourceAppName: String?,
        ignoreSensitive: Bool = true
    ) -> CapturedPayload? {
        if ignoreSensitive {
            let types = Set(pasteboard.pasteboardTypes.map { $0.rawValue })
            if !types.isDisjoint(with: Self.sensitivePasteboardTypes) {
                return nil
            }
        }

        let headerColor = AppColorExtractor.shared.dominantHeaderColor(for: sourceBundleID)

        // 1. Check File URLs (Finder, etc.)
        let fileURLs = pasteboard.fileURLs()
        if !fileURLs.isEmpty {
            let paths = fileURLs.map { $0.path }
            var totalBytes: Int64 = 0
            for url in fileURLs {
                if let attrs = try? FileManager.default.attributesOfItem(atPath: url.path),
                   let size = attrs[.size] as? Int64 {
                    totalBytes += size
                }
            }
            let hashInput = "file:" + paths.joined(separator: "|")
            let hash = sha256Hex(Data(hashInput.utf8))
            let item = ClipItem(
                type: .file,
                filePaths: paths,
                byteSize: totalBytes,
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: headerColor
            )
            return CapturedPayload(item: item, imageData: nil, rtfData: nil, htmlData: nil)
        }

        // 2. Check Image Data (unless rich/multi-line text dominates)
        let plainText = pasteboard.string(forType: .string)
        let trimmedText = plainText?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let hasSubstantialText = !trimmedText.isEmpty && (trimmedText.contains("\n") || (!trimmedText.hasPrefix("http") && trimmedText.count > 120))

        if !hasSubstantialText, let imageData = readImageData(from: pasteboard) {
            let hash = sha256Hex(imageData)
            let item = ClipItem(
                type: .image,
                byteSize: Int64(imageData.count),
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: headerColor
            )
            return CapturedPayload(item: item, imageData: imageData, rtfData: nil, htmlData: nil)
        }

        // 3. Check Link / URL
        if let urlString = extractSingleURL(from: pasteboard, plainText: plainText) {
            let hash = sha256Hex(Data(("link:" + urlString).utf8))
            let item = ClipItem(
                type: .link,
                textContent: urlString,
                urlString: urlString,
                byteSize: Int64(urlString.utf8.count),
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: headerColor
            )
            return CapturedPayload(item: item, imageData: nil, rtfData: nil, htmlData: nil)
        }

        // 4. Check Color String
        if let plainText, let parsedColor = ColorParser.parse(plainText) {
            let cleanText = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
            let hash = sha256Hex(Data(("color:" + parsedColor.hexString + ":" + cleanText).utf8))
            let item = ClipItem(
                type: .color,
                textContent: cleanText,
                parsedColor: parsedColor,
                byteSize: Int64(cleanText.utf8.count),
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: RGBColor(
                    red: parsedColor.red,
                    green: parsedColor.green,
                    blue: parsedColor.blue
                )
            )
            return CapturedPayload(item: item, imageData: nil, rtfData: nil, htmlData: nil)
        }

        // 5. Check Text (Plain / RTF / HTML)
        if let plainText, !plainText.isEmpty {
            let rtfData = pasteboard.data(forType: .rtf)
            let htmlData = pasteboard.data(forType: .html)
            let hash = sha256Hex(Data(("text:" + plainText).utf8))
            let item = ClipItem(
                type: .text,
                textContent: plainText,
                byteSize: Int64(plainText.utf8.count),
                hasRTF: rtfData != nil,
                hasHTML: htmlData != nil,
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: headerColor
            )
            return CapturedPayload(item: item, imageData: nil, rtfData: rtfData, htmlData: htmlData)
        }

        // Fallback: image even if text was present
        if let imageData = readImageData(from: pasteboard) {
            let hash = sha256Hex(imageData)
            let item = ClipItem(
                type: .image,
                byteSize: Int64(imageData.count),
                contentHash: hash,
                sourceAppBundleID: sourceBundleID,
                sourceAppName: sourceAppName,
                headerColorRGB: headerColor
            )
            return CapturedPayload(item: item, imageData: imageData, rtfData: nil, htmlData: nil)
        }

        return nil
    }

    private func readImageData(from pasteboard: PasteboardReadable) -> Data? {
        let preferredTypes: [NSPasteboard.PasteboardType] = [
            .png,
            NSPasteboard.PasteboardType("public.jpeg"),
            NSPasteboard.PasteboardType("public.heic"),
            NSPasteboard.PasteboardType("com.compuserve.gif"),
            .tiff
        ]
        for pType in preferredTypes {
            if let data = pasteboard.data(forType: pType), !data.isEmpty {
                // Convert raw TIFF screenshots to compact PNG for crisp disk storage
                if pType == .tiff,
                   let image = NSImage(data: data),
                   let tiff = image.tiffRepresentation,
                   let rep = NSBitmapImageRep(data: tiff),
                   let png = rep.representation(using: .png, properties: [:]) {
                    return png
                }
                return data
            }
        }
        return nil
    }

    private func extractSingleURL(from pasteboard: PasteboardReadable, plainText: String?) -> String? {
        if let urlStr = pasteboard.string(forType: .URL)?.trimmingCharacters(in: .whitespacesAndNewlines),
           let url = URL(string: urlStr),
           let scheme = url.scheme?.lowercased(),
           (scheme == "http" || scheme == "https"),
           url.host != nil {
            // Only classify as link if plain text isn't a longer multi-word paragraph
            if let plainText {
                let t = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
                if t == urlStr || (!t.contains(" ") && !t.contains("\n")) {
                    return urlStr
                }
            } else {
                return urlStr
            }
        }

        if let plainText {
            let trimmed = plainText.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty,
               !trimmed.contains(where: { $0.isWhitespace || $0.isNewline }),
               let url = URL(string: trimmed),
               let scheme = url.scheme?.lowercased(),
               (scheme == "http" || scheme == "https"),
               let host = url.host, host.contains(".") {
                return trimmed
            }
        }
        return nil
    }

    public func sha256Hex(_ data: Data) -> String {
        let digest = SHA256.hash(data: data)
        return digest.map { String(format: "%02x", $0) }.joined()
    }
}
